std::vector<Rgb> q(std::initializer_list<Rgb> src) {
    std::vector<Rgb> out;
    out.reserve(src.size());
    for (Rgb c : src) {
        out.push_back(MdColor::quantize(c));
    }
    if (!out.empty()) {
        out[0] = Rgb{0, 0, 0};
    }
    return out;
}

