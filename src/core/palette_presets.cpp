std::vector<Rgb> PalettePresets::colors_for(const std::string& name) {
    if (name == "4 - Ink") {
        return q({{0, 0, 0}, {73, 73, 73}, {182, 182, 182}, {255, 255, 255}});
    }
    if (name == "4 - Game Boy") {
        return q({{0, 0, 0}, {0, 73, 0}, {0, 255, 0}, {255, 255, 255}});
    }
    if (name == "4 - Amber") {
        return q({{0, 0, 0}, {146, 73, 0}, {255, 255, 0}, {255, 255, 255}});
    }
    if (name == "4 - Night") {
        return q({{0, 0, 0}, {0, 0, 109}, {0, 73, 255}, {255, 255, 255}});
    }
    if (name == "8 - Meadow") {
        return q({{0, 0, 0}, {0, 73, 0}, {0, 182, 0}, {0, 255, 0},
                  {109, 73, 36}, {255, 219, 0}, {255, 255, 0}, {255, 255, 255}});
    }
    if (name == "8 - Dungeon") {
        return q({{0, 0, 0}, {73, 0, 109}, {182, 0, 255}, {146, 0, 0},
                  {255, 0, 0}, {109, 73, 36}, {255, 109, 182}, {255, 255, 255}});
    }
    if (name == "8 - Coast") {
        return q({{0, 0, 0}, {0, 0, 109}, {0, 73, 255}, {0, 255, 255},
                  {0, 73, 73}, {255, 255, 0}, {255, 146, 219}, {255, 255, 255}});
    }
    if (name == "8 - Desert") {
        return q({{0, 0, 0}, {73, 36, 0}, {182, 73, 0}, {255, 146, 0},
                  {255, 255, 0}, {146, 0, 0}, {255, 0, 0}, {255, 255, 255}});
    }
    if (name == "8 - Magenta") {
        return q({{0, 0, 0}, {73, 0, 73}, {146, 0, 146}, {255, 0, 219},
                  {255, 109, 182}, {255, 0, 0}, {255, 255, 0}, {255, 255, 255}});
    }
    if (name == "12 - Forest") {
        return q({{0, 0, 0}, {0, 73, 0}, {0, 182, 36}, {0, 255, 0},
                  {109, 73, 36}, {255, 219, 0}, {255, 255, 0}, {0, 0, 109},
                  {0, 146, 255}, {146, 0, 0}, {255, 73, 73}, {255, 255, 255}});
    }
    if (name == "12 - Castle") {
        return q({{0, 0, 0}, {73, 73, 73}, {182, 182, 182}, {255, 255, 255},
                  {73, 0, 109}, {182, 0, 255}, {146, 0, 0}, {255, 0, 0},
                  {182, 109, 0}, {255, 219, 0}, {0, 0, 146}, {73, 146, 255}});
    }
    if (name == "12 - Tech") {
        return q({{0, 0, 0}, {36, 36, 73}, {73, 73, 109}, {0, 255, 255},
                  {0, 182, 255}, {0, 73, 255}, {0, 255, 0}, {182, 255, 0},
                  {255, 0, 219}, {255, 255, 0}, {255, 73, 0}, {255, 255, 255}});
    }
    if (name == "12 - Sunset") {
        return q({{0, 0, 0}, {73, 0, 36}, {146, 0, 0}, {255, 0, 0},
                  {255, 109, 0}, {255, 182, 0}, {255, 255, 0}, {255, 109, 182},
                  {255, 73, 219}, {146, 0, 182}, {219, 73, 255}, {255, 255, 255}});
    }
    if (name == "16 - Arcade") {
        return q({{0, 0, 0}, {73, 73, 73}, {146, 0, 0}, {255, 0, 0},
                  {255, 73, 0}, {255, 255, 0}, {0, 73, 0}, {0, 255, 0},
                  {0, 0, 109}, {0, 73, 255}, {0, 255, 255}, {182, 0, 255},
                  {255, 0, 219}, {255, 109, 182}, {182, 182, 182}, {255, 255, 255}});
    }
    if (name == "16 - Pastel") {
        return q({{0, 0, 0}, {73, 36, 73}, {73, 73, 109}, {255, 182, 219},
                  {255, 146, 219}, {182, 219, 255}, {109, 182, 255}, {182, 255, 182},
                  {109, 255, 109}, {255, 255, 182}, {255, 255, 109}, {219, 182, 255},
                  {182, 109, 255}, {255, 182, 146}, {182, 182, 182}, {255, 255, 255}});
    }
    return TilesetDoc::default_palette();
}

std::string PalettePresets::match_name(const std::vector<Rgb>& colors) {
    for (const auto& name : names()) {
        if (colors == colors_for(name)) {
            return name;
        }
    }
    return {};
}

